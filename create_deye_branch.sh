#!/bin/bash

# Скрипт создания новой ветки для Deye Gateway в SunPortal репозитории

echo "🚀 Создание новой ветки 'deye-gateway' в SunPortal репозитории..."

# Клонируем ваш репозиторий
echo "📥 Клонирование SunPortal репозитория..."
